
function CleanData(data){
    const cleanData = []
    
    for(const str of data){
        const s = str.split(" ");
        s.shift();
        cleanData.push(...s);
    }

    for(let i = 0; i < cleanData.length; i++){
        cleanData[i] = parseFloat(cleanData[i]);
    }

    return new Float32Array(cleanData);
}

